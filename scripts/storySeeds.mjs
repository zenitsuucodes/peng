export function buildStoryList() {
  const stories = storySeeds.map((s) => ({ ...s, core: [...s.core], imageQuery: [...s.imageQuery] }))
  while (stories.length < 100) {
    const base = storySeeds[stories.length % storySeeds.length]
    const n = stories.length + 1
    const suffix = ['update', 'field notes', 'what we know', 'explainer', 'outlook'][n % 5]
    stories.push({
      category: base.category,
      title: `${base.title}: ${suffix}`,
      lead: `${base.lead} Researchers published additional context as follow-up surveys continued.`,
      core: base.core.map((p, i) =>
        i === 0 ? `In related monitoring this season, ${p.charAt(0).toLowerCase()}${p.slice(1)}` : p,
      ),
      imageQuery: [...base.imageQuery],
    })
  }
  return stories.slice(0, 100)
}
